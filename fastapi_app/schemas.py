from typing import Any, Dict, Optional
from pydantic import BaseModel, Field

# --- Request Schemas ---

class AirflowPayload(BaseModel):
    dag_id: str = Field(
        ...,
        title="DAG ID",
        description="Unique identifier of the Airflow DAG sending the data.",
        examples=["daily_sales_etl"]
    )
    run_id: str = Field(
        ...,
        title="Run ID",
        description="Execution run ID generated by Airflow.",
        examples=["manual__2026-11-12T16:30:00+00:00"]
    )
    task_id: Optional[str] = Field(
        default=None,
        description="Optional task ID within the DAG.",
        examples=["push_metrics_to_mongo"]
    )
    data: Dict[str, Any] = Field(
        ...,
        description="Arbitrary key-value JSON metrics or task results.",
        examples=[{"rows_processed": 1540, "status": "success"}]
    )
    database: str = Field(
        default="airflow_data",
        description="Name of the Database.",
        examples=["job_db"])
    collection: str = Field(
        default="task_outputs",
        description="Name of the Collection.",
        examples=["clustered_collection"])

class TriggerJobRequest(BaseModel):
    job_name: str
    conf: Optional[Dict[str, Any]] = {}

# --- Response Schemas ---

class ClusterGetResponse(BaseModel):
    count: int = Field(..., examples=["1527"])
    items: list = Field(
        ...,
        description="List of MongoDB Docs",
        examples=[["doc1", "doc2", "doc3"]]
    )
class SaveResponse(BaseModel):
    status: str = Field(..., examples=["inserted"])
    id: str = Field(
        ...,
        description="MongoDB ObjectId string.",
        examples=["67338a1f9c4e2b0012a8d910"]
    )
    collection: str = Field(..., examples=["task_outputs"])

class ErrorResponse(BaseModel):
    detail: str = Field(..., examples=["MongoDB connection timed out"])